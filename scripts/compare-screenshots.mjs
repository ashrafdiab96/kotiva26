#!/usr/bin/env node
/* ============================================================
   Reference vs theme comparison for the KOTIVA port.

   Adapted from the reference's compare-screenshots.mjs. Its index-by-index match assumes two
   captures of the same DOM; Laravel and Salla pages differ in wrapper elements (Salla's
   hooks, modals, web components), so elements are matched by identity instead —
   tag + class + own text, then occurrence order — and compared on position, size, font,
   colour, visibility and image. Elements inside Salla's own components (the documented,
   allowed differences: buttons, quantity, gallery slider, reviews, installments) are
   excluded on both sides and counted separately.

   Usage: node scripts/compare-screenshots.mjs [--reference scratch/visual/reference]
                                               [--theme scratch/visual/theme] [--tol 0.5]
   Writes docs/VISUAL-REGRESSION.md. Exit 1 on any difference.
   ============================================================ */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CELLS, loadFamilies } from './lib/pages.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, def) => {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? def : process.argv[i + 1];
};
const refDir = path.resolve(ROOT, arg('reference', 'scratch/visual/reference'));
const themeDir = path.resolve(ROOT, arg('theme', 'scratch/visual/theme'));
const TOL = Number(arg('tol', '0.5'));
const { families } = loadFamilies(ROOT);

/* Fonts are compared by family + size + weight + style + letter-spacing + transform. */
const keyOf = (r) => `${r.tag}.${r.cls.trim().split(/\s+/).sort().join('.')}|${r.text}`;
function index(rows) {
  const seen = new Map();
  const out = new Map();
  for (const r of rows) {
    if (r.inSalla || r.w === 0 || r.h === 0) continue;
    const k = keyOf(r);
    const n = seen.get(k) || 0;
    seen.set(k, n + 1);
    out.set(`${k}#${n}`, r);
  }
  return out;
}

function compare(a, b) {
  const A = index(a.rows);
  const B = index(b.rows);
  const diffs = [];
  let matched = 0;
  for (const [k, x] of A) {
    const y = B.get(k);
    if (!y) { diffs.push(`missing in theme: <${x.tag} class="${x.cls}"> "${x.text}"`); continue; }
    matched++;
    const what = [];
    for (const p of ['x', 'y', 'w', 'h']) if (Math.abs(x[p] - y[p]) > TOL) what.push(`${p} ${x[p]} → ${y[p]}`);
    if (x.font !== y.font) what.push(`font ${x.font} → ${y.font}`);
    if (x.color !== y.color) what.push(`colour ${x.color} → ${y.color}`);
    if (x.vis !== y.vis) what.push(`visibility ${x.vis} → ${y.vis}`);
    const file = (s) => (s || '').split('?')[0].split('/').pop();
    if (file(x.src) !== file(y.src)) what.push(`image ${file(x.src)} → ${file(y.src)}`);
    if (what.length) diffs.push(`<${x.tag} class="${x.cls}"> "${x.text}": ${what.join('; ')}`);
  }
  for (const [k, y] of B) if (!A.has(k)) diffs.push(`extra in theme: <${y.tag} class="${y.cls}"> "${y.text}"`);
  const sallaRows = b.rows.filter((r) => r.inSalla).length;
  return { diffs, matched, total: A.size, sallaRows };
}

const rows = [];
let total = 0;
let missing = 0;
for (const f of families) {
  for (const c of CELLS) {
    const name = `${f.id}__${c.id}`;
    const pa = path.join(refDir, `${name}.geometry.json`);
    const pb = path.join(themeDir, `${name}.geometry.json`);
    if (!fs.existsSync(pa) || !fs.existsSync(pb)) { missing++; rows.push({ name, missing: true }); continue; }
    const a = JSON.parse(fs.readFileSync(pa, 'utf8'));
    const b = JSON.parse(fs.readFileSync(pb, 'utf8'));
    const r = compare(a, b);
    if (a.scrollWidth !== b.scrollWidth) r.diffs.unshift(`document width ${a.scrollWidth} → ${b.scrollWidth}`);
    if (Math.abs(a.scrollHeight - b.scrollHeight) > TOL) r.diffs.unshift(`document height ${a.scrollHeight} → ${b.scrollHeight}`);
    total += r.diffs.length;
    rows.push({ name, ...r });
    process.stdout.write(`  ${name}: ${r.matched}/${r.total} matched, ${r.diffs.length} difference(s), ${r.sallaRows} Salla-component elements excluded\n`);
  }
}

let md = '# Visual regression — reference vs theme\n\n';
md += 'Generated by `scripts/compare-screenshots.mjs` from `scripts/screenshot-pages.mjs` captures (reduced motion, lazy content scrolled in) for every page family × desktop 1440 / mobile 390 × light / dark. Elements are matched by tag + class + own text; Salla web-component internals are excluded (allowed differences, listed in docs/DECISIONS.md). Tolerance ±' + TOL + 'px.\n\n';
md += '| Capture | Matched | Differences | Salla elements excluded |\n|---|---|---|---|\n';
for (const r of rows) md += r.missing ? `| ${r.name} | — | capture missing | — |\n` : `| ${r.name} | ${r.matched}/${r.total} | ${r.diffs.length ? '**' + r.diffs.length + '**' : '0'} | ${r.sallaRows} |\n`;
md += `\n**Total differences: ${total}.** Missing capture pairs: ${missing}.\n\n`;
for (const r of rows.filter((x) => x.diffs && x.diffs.length)) {
  md += `## ${r.name}\n\n` + r.diffs.slice(0, 60).map((d) => `- ${d}`).join('\n') + (r.diffs.length > 60 ? `\n- … ${r.diffs.length - 60} more` : '') + '\n\n';
}
fs.writeFileSync(path.join(ROOT, 'docs/VISUAL-REGRESSION.md'), md);
console.log(`\n${total} difference(s), ${missing} missing pair(s) -> docs/VISUAL-REGRESSION.md`);
process.exit(total || missing ? 1 : 0);
